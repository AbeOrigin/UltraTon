/**
 * Writes compat/ssrf-corpus/RESULTS.md: every case of the corpus against every client. Run from compat/ with
 * `npm run corpus` (loopback only, like the tests). Commit the result with the change that moved it.
 */
import fs from 'node:fs';
import net from 'node:net';
import { CASES, clients, runCorpus, type Outcome, type BlockReason } from './corpus.ts';

const ipv6 = await new Promise<boolean>(resolve => {
    const probe = net.createServer();
    probe.once('error', () => resolve(false));
    probe.listen(0, '::1', () => probe.close(() => resolve(true)));
});

const results = await runCorpus(ipv6);
const clientNames = clients().map(c => c.name);
const reasonText: Record<BlockReason, string> = { 'reserved-ip': 'reserved IP', 'plain-http': 'plain http', credentials: 'credentials in URL' };
const cell = (caseId: string, client: string) => {
    const r = results.find(x => x.caseId === caseId && x.client === client);
    if (!r) return '—';
    const marks: Record<Outcome, string> = {
        blocked: `✅ blocked (${reasonText[r.detail as BlockReason] ?? r.detail})`,
        reached: '❌ reached',
        attempted: '❌ attempted',
        error: `⚠️ error (${r.detail})`,
    };
    return marks[r.outcome];
};

const version = (name: string) => JSON.parse(fs.readFileSync(new URL(`../node_modules/${name}/package.json`, import.meta.url), 'utf8')).version;
const rows = CASES.map(c => {
    if (c.ipv6 && !ipv6) return `| ${c.description} | ${clientNames.map(() => 'n/a (no IPv6 loopback)').join(' | ')} |`;
    return `| [${c.description}](${c.source}) | ${clientNames.map(n => cell(c.id, n)).join(' | ')} |`;
});
const lines = [
    '# SSRF corpus results',
    '',
    `Generated by \`npm run corpus\` in \`compat/\` on Node ${process.version} (undici ${process.versions.undici}, used by Node's \`fetch\`), with ultraton ${version('ultraton')}, axios ${version('axios')}, got ${version('got')} and node-fetch ${version('node-fetch')}. Cases and harness: [corpus.ts](corpus.ts); each case links to its source.`,
    '',
    '**How it runs.** Everything stays on loopback. Canary servers on 127.0.0.1 (http and https) and ::1 record every request and every TCP connection, DNS is mocked, and a sandbox refuses any connection to a non-loopback address. Clients run one at a time.',
    '',
    '**Outcomes.**',
    '- **✅ blocked (reason):** the client refused the request before connecting, and the reason is the one the case is about. A reserved-IP case blocked by the plain-http rule would not count.',
    '- **❌ reached:** the request reached a canary, or opened a TCP connection to one (for https, before the TLS check failed).',
    '- **❌ attempted:** the client tried to connect to a non-loopback internal address, such as cloud metadata, and only the test sandbox refused it. In production that connection would have been made. Whether it then leaks data depends on the endpoint: AWS IMDSv2, for one, answers a GET without a token with 401.',
    '- **⚠️ error:** the request failed for another reason; it says nothing either way.',
    '- **—:** not measured. The mixed DNS answer is about how a validating client judges an answer, so it only runs against the protected clients.',
    '',
    '**Setup.**',
    '- Protected clients allow only `redirector.localhost`, the first hop of the redirect cases.',
    '- Unprotected clients keep their defaults, with three changes for a deterministic run: axios with `proxy: false` (no proxy from the environment), got without retries, and a 3 s timeout for all of them. Redirects are followed with each client\'s defaults; UltraTon follows up to 5.',
    '',
    'The unprotected libraries are not *meant* to block SSRF: defending against it is not their goal. The table shows what you get by default, and what `createSecureAgents()` adds without changing clients.',
    '',
    `| Case | ${clientNames.join(' | ')} |`,
    `|---|${clientNames.map(() => '---').join('|')}|`,
    ...rows,
    '',
];
fs.writeFileSync(new URL('./RESULTS.md', import.meta.url), lines.join('\n').replace(/\n/g, '\r\n'));
console.log(rows.join('\n'));
